CREATE DATABASE IF NOT EXISTS pyplatform CHARACTER SET utf8mb4;
USE pyplatform;
CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, email VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(200) NOT NULL, role ENUM('ADMIN','INSTRUCTOR','STUDENT') NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS exercises(
  id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(120) NOT NULL, description TEXT NOT NULL,
  difficulty ENUM('EASY','MEDIUM','HARD') NOT NULL, starter_code TEXT, expected_output TEXT NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING', created_by INT NOT NULL,
  section ENUM('BASIC','MEDIUM','ADVANCED') NOT NULL DEFAULT 'BASIC',
  sample_input TEXT, sort_order INT NOT NULL DEFAULT 0,
  level_name VARCHAR(80), topic VARCHAR(120), learn_text TEXT, solution_code TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS submissions(
  id INT AUTO_INCREMENT PRIMARY KEY, exercise_id INT NOT NULL, student_id INT NOT NULL, code MEDIUMTEXT NOT NULL,
  passed BOOLEAN NOT NULL, output TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(exercise_id) REFERENCES exercises(id) ON DELETE CASCADE, FOREIGN KEY(student_id) REFERENCES users(id) ON DELETE CASCADE);
